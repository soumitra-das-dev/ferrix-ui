//! Rust code generator translating FSX AST into native ferrix-core component code.

use crate::ast::*;

pub struct Codegen;

impl Codegen {
    pub fn new() -> Self {
        Self
    }

    pub fn generate(&self, source_file: &SourceFile) -> String {
        let mut out = String::new();
        out.push_str("// AUTO-GENERATED BY FERRIX COMPILER. DO NOT EDIT.\n");
        out.push_str("use ferrix_core::prelude::*;\n\n");

        // 1. Generate Type declarations
        for ty in &source_file.types {
            out.push_str("#[derive(Clone, Debug, PartialEq)]\n");
            out.push_str(&format!("pub struct {} {{\n", ty.name));
            for field in &ty.fields {
                let rust_type = match &field.type_ref {
                    TypeRef::Primitive(p) => match p.as_str() {
                        "i32" | "i64" | "u32" | "u64" | "f32" | "f64" | "bool" | "String" => {
                            p.clone()
                        }
                        other => other.to_string(),
                    },
                    TypeRef::Custom(c) => c.clone(),
                    TypeRef::List(inner) => format!("Vec<{}>", self.type_ref_to_rust(inner)),
                    TypeRef::Option(inner) => format!("Option<{}>", self.type_ref_to_rust(inner)),
                };
                out.push_str(&format!("    pub {}: {},\n", field.name, rust_type));
            }
            out.push_str("}\n\n");
        }

        // 2. Generate Component functions
        for comp in &source_file.components {
            let props_arg = match &comp.props_param {
                Some((param, ty)) => format!(", {}: {}", param, self.type_ref_to_rust(ty)),
                None => String::new(),
            };

            out.push_str("#[allow(non_snake_case)]\n");
            out.push_str(&format!(
                "pub fn {}(cx: &mut ComponentContext{}) -> Element {{\n",
                comp.name, props_arg
            ));
            out.push_str("    cx.prepare_render();\n\n");

            // Generate hook statements
            for stmt in &comp.statements {
                match stmt {
                    Statement::Hook(hook) => {
                        let rust_hook = match hook.hook_name.as_str() {
                            "useState" => "use_state",
                            "useSignal" => "use_signal",
                            "useRef" => "use_ref",
                            "useMemo" => "use_memo",
                            "useEffect" => "use_effect",
                            other => other,
                        };
                        let args: Vec<String> =
                            hook.args.iter().map(|a| self.expr_to_rust(a)).collect();
                        out.push_str(&format!(
                            "    let {} = cx.{}({});\n",
                            hook.ident,
                            rust_hook,
                            args.join(", ")
                        ));
                    }
                    Statement::Let { ident, value, .. } => {
                        out.push_str(&format!(
                            "    let {} = {};\n",
                            ident,
                            self.expr_to_rust(value)
                        ));
                    }
                    Statement::Expr(expr) => {
                        out.push_str(&format!("    {};\n", self.expr_to_rust(expr)));
                    }
                }
            }
            out.push('\n');

            // Generate return element tree
            let elem_code = self.element_to_rust(&comp.return_elem, 1);
            out.push_str(&format!(
                "    {}.build_with_id(NodeId::new(1), cx.allocator())\n",
                elem_code
            ));
            out.push_str("}\n\n");
        }

        out
    }

    fn type_ref_to_rust(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::Primitive(p) => p.clone(),
            TypeRef::Custom(c) => c.clone(),
            TypeRef::List(inner) => format!("Vec<{}>", self.type_ref_to_rust(inner)),
            TypeRef::Option(inner) => format!("Option<{}>", self.type_ref_to_rust(inner)),
        }
    }

    fn element_to_rust(&self, elem: &FsxElement, indent: usize) -> String {
        let pad = "    ".repeat(indent);
        let mut lines = Vec::new();

        // Builder initialization
        lines.push(format!("{}::new()", elem.tag_name));

        // Attributes
        for attr in &elem.attributes {
            let val = match &attr.value {
                AttrValue::Literal(Expr::Int(i, _)) => format!("{:.1}", *i as f64),
                AttrValue::Literal(Expr::Float(f, _)) => format!("{:.1}", f),
                AttrValue::Literal(Expr::StringLit(s, _)) => format!("\"{}\"", s),
                AttrValue::Literal(Expr::Bool(b, _)) => format!("{}", b),
                AttrValue::Literal(other) => self.expr_to_rust(other),
                AttrValue::Expr(Expr::ArrowFn { .. }) => {
                    // Event handler
                    continue;
                }
                AttrValue::Expr(Expr::Int(i, _)) => {
                    if attr.name == "padding" || attr.name == "spacing" || attr.name == "size" {
                        format!("{:.1}", *i as f64)
                    } else {
                        format!("{}", i)
                    }
                }
                AttrValue::Expr(Expr::Float(f, _)) => format!("{:.1}", f),
                AttrValue::Expr(expr) => self.expr_to_rust(expr),
            };

            match attr.name.as_str() {
                "padding" => lines.push(format!(".padding({})", val)),
                "spacing" => lines.push(format!(".spacing({})", val)),
                "size" => lines.push(format!(".size({})", val)),
                "color" => lines.push(format!(".color({})", val)),
                "backgroundColor" => lines.push(format!(".background_color({})", val)),
                "textColor" => lines.push(format!(".text_color({})", val)),
                "enabled" => lines.push(format!(".enabled({})", val)),
                "key" => lines.push(format!(".key({})", val)),
                other => lines.push(format!(".{}({})", other, val)),
            }
        }

        // Children and Text Content
        let mut text_parts = Vec::new();
        let mut child_elems = Vec::new();

        for child in &elem.children {
            match child {
                FsxChild::Text(t) => {
                    text_parts.push(format!("\"{}\"", t));
                }
                FsxChild::Expr(expr) => {
                    text_parts.push(self.expr_to_rust(expr));
                }
                FsxChild::Element(child_elem) => {
                    child_elems.push(child_elem);
                }
            }
        }

        // For Text or Button nodes, format text content
        if !text_parts.is_empty() && (elem.tag_name == "Text" || elem.tag_name == "Button") {
            if text_parts.len() == 1 && text_parts[0].starts_with('"') {
                lines[0] = format!("{}::new({})", elem.tag_name, text_parts[0]);
            } else {
                // Interpolated string: format!("Count: {}", count.get())
                let mut fmt_string = String::new();
                let mut fmt_args = Vec::new();
                for part in &elem.children {
                    match part {
                        FsxChild::Text(t) => fmt_string.push_str(t),
                        FsxChild::Expr(expr) => {
                            fmt_string.push_str("{}");
                            fmt_args.push(self.expr_to_rust(expr));
                        }
                        _ => {}
                    }
                }
                lines[0] = format!(
                    "{}::new(format!(\"{}\", {}))",
                    elem.tag_name,
                    fmt_string,
                    fmt_args.join(", ")
                );
            }
        }

        // Nested child elements
        for child_elem in child_elems {
            let child_code = self.element_to_rust(child_elem, indent + 1);
            lines.push(format!(".child({})", child_code));
        }

        lines.join(&format!("\n{}", pad))
    }

    fn expr_to_rust(&self, expr: &Expr) -> String {
        match expr {
            Expr::Ident(s, _) => s.clone(),
            Expr::Int(i, _) => format!("{}", i),
            Expr::Float(f, _) => format!("{}", f),
            Expr::StringLit(s, _) => format!("\"{}\"", s),
            Expr::Bool(b, _) => format!("{}", b),
            Expr::Member(parent, member, _) => {
                let parent_str = self.expr_to_rust(parent);
                if member == "value" {
                    format!("{}.get()", parent_str)
                } else {
                    format!("{}.{}", parent_str, member)
                }
            }
            Expr::Call(callee, args, _) => {
                let callee_str = self.expr_to_rust(callee);
                let args_str: Vec<String> = args.iter().map(|a| self.expr_to_rust(a)).collect();
                format!("{}({})", callee_str, args_str.join(", "))
            }
            Expr::ArrowFn { params, body, .. } => {
                let body_str = self.expr_to_rust(body);
                format!("|{}| {}", params.join(", "), body_str)
            }
            Expr::Binary {
                left, op, right, ..
            } => {
                let left_str = self.expr_to_rust(left);
                let right_str = self.expr_to_rust(right);
                let op_str = match op {
                    BinaryOp::Add => "+",
                    BinaryOp::Sub => "-",
                    BinaryOp::Mul => "*",
                    BinaryOp::Div => "/",
                    BinaryOp::Eq => "==",
                    BinaryOp::NotEq => "!=",
                    BinaryOp::Lt => "<",
                    BinaryOp::Gt => ">",
                };
                format!("{} {} {}", left_str, op_str, right_str)
            }
        }
    }
}

impl Default for Codegen {
    fn default() -> Self {
        Self::new()
    }
}
